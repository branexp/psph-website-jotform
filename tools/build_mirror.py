#!/usr/bin/env python3
"""Build the campaign-mirror variant of the site (the k12*.org domains).

The mirrors serve the same content as psph.org with two differences:
  * the booking page is the homepage (/), and the regular homepage moves to /home;
  * search engines are told not to index them (X-Robots-Tag noindex), and they
    carry no canonical/og:url tags or sitemap.

Usage: python3 tools/build_mirror.py OUTPUT_DIR
The repository itself stays a plain static site; this only writes OUTPUT_DIR.
"""
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXCLUDE_PREFIXES = (".github/", "tools/")
EXCLUDE_FILES = {".gitattributes", "screenshot-audit.js", "sitemap.xml", "robots.txt", ".htaccess"}

ROBOTS = "User-agent: *\nAllow: /\n"

HTACCESS = r"""# Campaign mirror of psph.org (generated by tools/build_mirror.py; do not edit on the server)
RewriteEngine On
Options -MultiViews

# --- Canonical: HTTPS + non-www for whichever mirror domain this is ---
RewriteCond %{HTTP_HOST} ^www\.(.+)$ [NC]
RewriteRule ^ https://%1%{REQUEST_URI} [R=301,L]
RewriteCond %{HTTPS} !=on
RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]

# --- The booking page is the homepage on mirrors ---
RewriteRule ^schedule/?$ / [R=301,L]

# --- Remove trailing slashes (except root) ---
RewriteCond %{REQUEST_URI} !^/$
RewriteCond %{REQUEST_FILENAME} !-d
RewriteRule ^(.+?)/$ /$1 [R=301,L]

# --- Redirect .html extension to clean URLs ---
RewriteCond %{THE_REQUEST} \s/+(.+?)\.html[\s?] [NC]
RewriteRule ^ /%1 [R=301,L]

# --- Short-circuit actual files/dirs ---
RewriteCond %{REQUEST_FILENAME} -f [OR]
RewriteCond %{REQUEST_FILENAME} -d
RewriteRule ^ - [L]

# --- Serve extensionless URLs as .html ---
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_FILENAME} !-d
RewriteCond %{REQUEST_FILENAME}.html -f
RewriteRule ^(.+?)$ $1.html [L]

ErrorDocument 404 /404.html

<IfModule mod_headers.c>
  # Campaign mirrors should not be indexed by search engines.
  Header always set X-Robots-Tag "noindex,follow"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"

  <FilesMatch "\.(html?)$">
    Header set Cache-Control "no-cache, max-age=0, must-revalidate"
  </FilesMatch>

  <FilesMatch "\.(jpe?g|png|svg|webp|ico)$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>

  <FilesMatch "\.(css|js|woff2?|ttf)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
</IfModule>
"""


def remap_links(text: str) -> str:
    """Swap the homepage and booking page URLs: / -> /home, /schedule -> /."""
    placeholder = "\x00BOOKING\x00"
    text = re.sub(r'(["\'])/schedule(["\'#?])', lambda m: m.group(1) + placeholder + m.group(2), text)
    text = re.sub(r'(href=")/(["#])', r"\1/home\2", text)
    return text.replace(placeholder, "/")


def strip_canonical(html: str) -> str:
    """Drop canonical/og:url and add a robots meta tag.

    The meta tag backs up the X-Robots-Tag header: mirror domains proxied
    through Cloudflare reach visitors without the header even though the
    origin sends it.
    """
    html = re.sub(r'\n\s*<link rel="canonical"[^>]*>', "", html)
    html = re.sub(r'\n\s*<meta name="robots"[^>]*>', "", html)
    html = re.sub(r'\n\s*<meta property="og:url"[^>]*>', "", html)
    return html.replace('<meta name="viewport"', '<meta name="robots" content="noindex,follow">\n  <meta name="viewport"', 1)


def tracked_files():
    out = subprocess.run(["git", "ls-files"], cwd=ROOT, check=True, capture_output=True, text=True).stdout
    for name in out.splitlines():
        if name in EXCLUDE_FILES or name.startswith(EXCLUDE_PREFIXES):
            continue
        yield name


def main(out_dir: str) -> None:
    out = Path(out_dir)
    if out.exists():
        shutil.rmtree(out)
    rename = {"index.html": "home.html", "schedule.html": "index.html"}
    for name in tracked_files():
        src = ROOT / name
        dst = out / rename.get(name, name)
        dst.parent.mkdir(parents=True, exist_ok=True)
        if name.endswith(".html"):
            dst.write_text(strip_canonical(remap_links(src.read_text())))
        elif name == "scripts/main.js":
            dst.write_text(remap_links(src.read_text()))
        else:
            shutil.copy2(src, dst)
    (out / ".htaccess").write_text(HTACCESS)
    (out / "robots.txt").write_text(ROBOTS)

    # Guard: no mirror page may still point visitors at the old URLs.
    for page in out.glob("*.html"):
        text = page.read_text()
        assert '"/schedule' not in text, f"{page.name} still links to /schedule"
        assert 'rel="canonical"' not in text, f"{page.name} still has a canonical tag"
        assert text.count('<meta name="robots" content="noindex,follow">') == 1, f"{page.name} lacks robots meta"
    assert "'/schedule'" not in (out / "scripts/main.js").read_text()
    print(f"mirror built in {out}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: build_mirror.py OUTPUT_DIR")
    main(sys.argv[1])
